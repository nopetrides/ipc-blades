using System.Collections.Generic;
using BladeContact;
using FIMSpace.FProceduralAnimation;
using UnityEngine;

/// <summary>
///     Tells a sword's <see cref="BladeShell" /> which shapes are carrying its blade while Ragdoll
///     Animator is wearing it.
/// </summary>
/// <remarks>
///     <para>
///         <b>Why this exists.</b> When <see cref="RA2AttachableObject" /> is worn, Ragdoll Animator does
///         not move the sword's own body. It sets that body kinematic, switches every authored collider
///         off, and builds a rigid copy — one new GameObject per authored collider, plus a root carrying
///         a Rigidbody and a FixedJoint to the hand bone — parented under the PHYSICAL dummy skeleton.
///         Every contact from then on is generated by shapes the authored sword has never heard of.
///     </para>
///     <para>
///         Nothing errors when that happens. A layer keyed on the authored collider simply never matches
///         a contact, never forms a pair, and reports nothing, so the station looks like it is running
///         ordinary PhysX by design rather than by omission. That is exactly what was happening at the
///         three OurSolution stations.
///     </para>
///     <para>
///         <b>Why the mapping is by index.</b> Ragdoll Animator builds its generated list by walking
///         <see cref="RA2AttachableObject.AttachableColliders" /> in order and appending one copy per
///         entry, so entry <i>i</i> of one list is entry <i>i</i> of the other. Matching by name would
///         also work today and would break the first time two shapes share a name; matching by mesh would
///         break on the QuickDirty hulls, which are derived from the same source mesh.
///     </para>
///     <para>
///         <b>Only the blade is declared.</b> The generated list also holds the crossguard and the marker
///         spheres. Handing those to the shell would make a guard contact classify as a blade contact and
///         receive a blade's tangential response.
///     </para>
///     <para>
///         This is a consumer-side adapter on purpose. The BladeContact package must not know that
///         Ragdoll Animator exists; it exposes <see cref="BladeShell.BindPhysicsProxy" /> and this
///         supplies the answer for this project.
///     </para>
/// </remarks>
[DisallowMultipleComponent]
[RequireComponent(typeof(BladeShell))]
public sealed class RqRagdollAttachableBinding : MonoBehaviour
{
    [Tooltip("The attachable this sword is worn by. Left empty, the one on this object is used.")]
    [SerializeField] private RA2AttachableObject attachable;

    [Tooltip("Further authored colliders that are also THIS BLADE. Their generated copies are declared " +
             "alongside the blade's. Crossguard, grip, pommel and marker colliders must never be listed.")]
    [SerializeField] private Collider[] additionalBladeColliders = new Collider[0];

    private BladeShell shell;
    private GameObject boundTo;
    private readonly List<Collider> proxyBlades = new List<Collider>();

    /// <summary>The generated physics root currently bound, or null while the sword is not worn.</summary>
    public GameObject BoundTo => boundTo;

    private void Awake()
    {
        shell = GetComponent<BladeShell>();
        if (attachable == null) attachable = GetComponent<RA2AttachableObject>();
    }

    private void OnDisable()
    {
        if (boundTo == null) return;

        boundTo = null;
        if (shell != null) shell.UnbindPhysicsProxy();
    }

    /// <summary>
    ///     Rebinds when, and only when, the generated physics object changes identity.
    /// </summary>
    /// <remarks>
    ///     Polled rather than event-driven because Ragdoll Animator raises no public signal for the wear
    ///     that happens during its own initialisation. The check is a reference comparison; the binding
    ///     work runs on the two frames a sword is picked up and put down.
    /// </remarks>
    private void LateUpdate()
    {
        GameObject generated = attachable != null ? attachable.GeneratedPhysicsObject : null;
        if (generated == boundTo) return;

        boundTo = generated;

        if (generated == null)
        {
            shell.UnbindPhysicsProxy();
            return;
        }

        if (!TryCollectProxyBlades())
        {
            shell.UnbindPhysicsProxy();
            return;
        }

        Rigidbody proxyBody = attachable.lastRigidbody;
        if (proxyBody == null) proxyBody = generated.GetComponent<Rigidbody>();

        shell.BindPhysicsProxy(proxyBody, generated.transform, proxyBlades);
    }

    /// <summary>Maps this blade's authored colliders onto their generated copies, by list index.</summary>
    private bool TryCollectProxyBlades()
    {
        proxyBlades.Clear();

        List<Collider> authored = attachable.AttachableColliders;
        List<Collider> generated = attachable.GeneratedPhysicsColliders;

        if (authored == null || generated == null || authored.Count != generated.Count)
        {
            Debug.LogWarning(
                "[L2] " + name + ": Ragdoll Animator's generated collider list does not correspond to " +
                "the authored one (" + (authored == null ? 0 : authored.Count) + " authored vs " +
                (generated == null ? 0 : generated.Count) + " generated), so this blade cannot be matched " +
                "to the shapes now carrying it. It stays entirely with ordinary PhysX.", this);
            return false;
        }

        for (int i = 0; i < authored.Count; i++)
            if (IsThisBlade(authored[i]) && generated[i] != null)
                proxyBlades.Add(generated[i]);

        if (proxyBlades.Count == 0)
        {
            Debug.LogWarning(
                "[L2] " + name + ": the blade collider named by BladeShell is not in this attachable's " +
                "AttachableColliders list, so no generated copy of it exists. It stays entirely with " +
                "ordinary PhysX.", this);
            return false;
        }

        return true;
    }

    private bool IsThisBlade(Collider authored)
    {
        if (authored == null) return false;
        if (authored == shell.BladeCollider) return true;

        for (int i = 0; i < additionalBladeColliders.Length; i++)
            if (additionalBladeColliders[i] == authored) return true;

        return false;
    }
}
